// Generates catalog_seed.sql from the app's bundled catalog.json (idempotent upserts).
import { readFileSync } from "node:fs";
const url = new URL("../../android/app/src/main/assets/catalog.json", import.meta.url);
const catalog = JSON.parse(readFileSync(url, "utf8"));
const lit = (v) => "'" + JSON.stringify(v).replaceAll("'", "''") + "'::jsonb";
const out = ["-- Generated by backend/scripts/gen_seed.mjs from android/app/src/main/assets/catalog.json"];
catalog.recipes.forEach((r, i) => {
  out.push(`insert into public.recipes(id, doc, published, published_at, sort_hint) values ('${r.id}', ${lit(r)}, true, '2026-11-01T00:00:00Z', ${i * 10})
  on conflict (id) do update set doc = excluded.doc;`);
});
for (const g of catalog.appGroups) {
  out.push(`insert into public.app_groups(id, doc) values ('${g.id}', ${lit(g)})
  on conflict (id) do update set doc = excluded.doc;`);
}
console.log(out.join("\n"));
